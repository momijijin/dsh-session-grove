// Build the client half into a single ModuleLoader bundle.
// The platform loader expects:
//   window.__ModuleLoader__.load({ id, factory: (require) => module.exports })
// and provides react / react/jsx-runtime as externals.
import { build } from 'esbuild'
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const outfile = resolve(root, 'lib/client.js')

const result = await build({
  entryPoints: [resolve(root, 'src/client/index.js')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  legalComments: 'none',
  external: [
    'react',
    'react/jsx-runtime',
    '@deepseek-ai/dsh-client-ui-primitives',
    '@deepseek-ai/dsh-client-store',
  ],
})

const code = result.outputFiles[0].text
const wrapped = `// generated by scripts/build-client.mjs - do not edit\nwindow.__ModuleLoader__.load({\n  id: 'dsh-session-groups',\n  factory: (require) => {\n    const module = { exports: {} };\n    const exports = module.exports;\n    (function (module, exports, require) {\n${code}\n    })(module, exports, require);\n    return module.exports;\n  }\n});\n`

await mkdir(dirname(outfile), { recursive: true })
await writeFile(outfile, wrapped, 'utf8')
console.log(`built ${outfile} (${wrapped.length} bytes)`)
