// Build the client half into a ModuleLoader bundle plus lazy locale chunks.
// The platform loader expects:
//   window.__ModuleLoader__.load({ id, factory: (require) => module.exports })
// and supports package-local chunks via require.async('./client.<name>.js').
import { build } from 'esbuild'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const outDir = process.env.DSH_GROVE_BUILD_OUT ? resolve(process.env.DSH_GROVE_BUILD_OUT) : resolve(root, 'lib')
const outfile = resolve(outDir, 'client.js')
const lazyResources = resolve(root, 'src/client/i18n/resources-lazy.js')

// The static resources module stays the Node/test truth; the browser bundle
// aliases it to the en/zh-only loader so the other dictionaries become chunks.
const lazyLocalePlugin = {
  name: 'lazy-locale-resources',
  setup(build) {
    build.onResolve({ filter: /(^|\/)resources\.js$/ }, (args) => {
      if (args.path.endsWith('resources.js') && !args.path.endsWith('resources-lazy.js')) return { path: lazyResources }
      return undefined
    })
  },
}

const result = await build({
  entryPoints: [resolve(root, 'src/client/index.js')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  charset: 'utf8',
  legalComments: 'none',
  plugins: [lazyLocalePlugin],
  external: [
    'react',
    'react/jsx-runtime',
    '@deepseek-ai/dsh-client-ui-primitives',
    '@deepseek-ai/dsh-client-store',
  ],
})

const code = result.outputFiles[0].text
const wrapped = `// generated by scripts/build-client.mjs - do not edit
window.__ModuleLoader__.load({
  id: 'dsh-session-grove',
  factory: (require) => {
    const module = { exports: {} };
    const exports = module.exports;
    (function (module, exports, require) {
${code}
    })(module, exports, require);
    return module.exports;
  }
});
`

await mkdir(dirname(outfile), { recursive: true })
await writeFile(outfile, wrapped, 'utf8')

const lazyFiles = {
  ja: 'ja.json',
  ko: 'ko.json',
  de: 'de.json',
  fr: 'fr.json',
  es: 'es.json',
  pt: 'pt.json',
  it: 'it.json',
  nl: 'nl.json',
  pl: 'pl.json',
  tr: 'tr.json',
  vi: 'vi.json',
  th: 'th.json',
  id: 'id.json',
  ru: 'ru.json',
  hi: 'hi.json',
  ar: 'ar.json',
  'zh-Hant': 'zh-Hant.json',
}
let chunkBytes = 0
for (const [language, file] of Object.entries(lazyFiles)) {
  const dictionary = JSON.parse(await readFile(resolve(root, 'locale', file), 'utf8'))
  const chunkName = 'client.locale-' + language + '.js'
  const chunk = `// generated by scripts/build-client.mjs - do not edit
window.__ModuleLoader__.load({
  id: 'dsh-session-grove',
  chunk: '${chunkName}',
  factory: () => ({ language: '${language}', dictionary: ${JSON.stringify(dictionary)} })
});
`
  const target = resolve(outDir, chunkName)
  await writeFile(target, chunk, 'utf8')
  chunkBytes += Buffer.byteLength(chunk)
}
console.log('built ' + outfile + ' (' + wrapped.length + ' bytes)')
console.log('built ' + Object.keys(lazyFiles).length + ' lazy locale chunks (' + chunkBytes + ' bytes)')
